#Requires -Version 7.0
<#
.SYNOPSIS
    Generate the assembly-level NativeApi declarations for the safe-native CRT exports.

.DESCRIPTION
    Reads docs/crt-api-classification.csv, keeps rows whose status is "safe-native", and emits
    src/ImaginedNT.Apis.Crt/CrtNativeApis.cs. Each declaration also gets a ucrtbase!name alias so
    guests that import the backing DLL directly are covered by NativeApiPolicy.DeclaredOnly.

    The CSV is the curated source of truth; do not hand-edit the generated C# file.

.PARAMETER Csv
    Classified CSV path. Defaults to docs/crt-api-classification.csv under the repo root.

.PARAMETER Out
    Generated C# path. Defaults to src/ImaginedNT.Apis.Crt/CrtNativeApis.cs under the repo root.

.EXAMPLE
    pwsh -File scripts/generate-crt-native-declarations.ps1
#>
[CmdletBinding()]
param(
    [string] $Csv,
    [string] $Out
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $Csv) { $Csv = Join-Path $repoRoot 'docs/crt-api-classification.csv' }
if (-not $Out) { $Out = Join-Path $repoRoot 'src/ImaginedNT.Apis.Crt/CrtNativeApis.cs' }

if (-not (Test-Path -LiteralPath $Csv)) { throw "classification CSV not found: $Csv" }

$rows = Import-Csv -LiteralPath $Csv |
    Where-Object { $_.status -eq 'safe-native' } |
    Sort-Object module, name

if ($rows.Count -eq 0) { throw "no safe-native rows in $Csv" }

function ConvertTo-CSharpString([string] $value) {
    return $value.Replace('\', '\\').Replace('"', '\"')
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// <auto-generated />')
$lines.Add('// Generated from docs/crt-api-classification.csv by scripts/generate-crt-native-declarations.ps1.')
$lines.Add("// $($rows.Count) safe-native UCRT exports; each also declares a ucrtbase!name alias.")
$lines.Add('')
$lines.Add('using ImaginedNT.Core.Runtime;')
$lines.Add('')

foreach ($row in $rows) {
    $module = ConvertTo-CSharpString $row.module
    $name = ConvertTo-CSharpString $row.name
    $alias = ConvertTo-CSharpString ("ucrtbase!" + $row.name)
    $lines.Add("[assembly: NativeApi(`"$module`", `"$name`", ApiCategory.System, `"$alias`")]")
}

$lines.Add('')
$lines.Add('namespace ImaginedNT.Apis.Crt;')
$lines.Add('')
$lines.Add('/// <summary>')
$lines.Add('/// Assembly marker for the generated UCRT native declarations. The declarations themselves')
$lines.Add('/// are assembly-level <see cref="NativeApiAttribute"/> instances in this file.')
$lines.Add('/// </summary>')
$lines.Add('public static class CrtNativeApis')
$lines.Add('{')
$lines.Add('}')

$directory = Split-Path -Parent $Out
if ($directory) { New-Item -ItemType Directory -Force -Path $directory | Out-Null }
Set-Content -LiteralPath $Out -Value $lines -Encoding utf8
Write-Host "wrote $($rows.Count) declarations to $Out"
